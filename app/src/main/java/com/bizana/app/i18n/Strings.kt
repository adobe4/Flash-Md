val LocalStr = staticCompositionLocalOf { EN }

fun strFor(lang: String?): Str = if (lang == "sw") SW else EN

fun Str.statusLabel(status: String): String = when (status) {
    "draft" -> draft; "sent" -> sent; "paid" -> paid; "overdue" -> overdue; "cancelled" -> cancelled
    else -> status
}

fun Str.methodLabel(m: String): String = when (m) {
    "cash" -> cash; "mpesa" -> mpesa; "bank" -> bank; else -> otherW
}

fun Str.expCatLabel(c: String): String = when (c) {
    "stock" -> stock; "transport" -> transport; "rent" -> rent; "salaries" -> salaries
    "marketing" -> marketing; "utilities" -> utilities; else -> otherW
}

fun Str.unitLabel(u: String): String = when (u) {
    "piece" -> piece; "hour" -> hour; "kg" -> kg; "month" -> month; "service" -> service
    else -> u
}
